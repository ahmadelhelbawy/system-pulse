// Consolidates ts-rs's per-type output (crates/system-pulse-core/src/**,
// exported via `#[derive(TS)] #[ts(export)]`) into the single
// src/lib/contracts.ts file the frontend imports from.
//
// Why consolidate at all: ts-rs generates one .ts file per Rust type with
// cross-file `import type { X } from "./X"` statements between them. That's
// a fine layout for a dedicated bindings package, but this repo's frontend
// (and its existing code) imports everything from one `contracts.ts`
// module, so this script strips the now-redundant imports (everything ends
// up in one file) and concatenates the type declarations in a stable order.
//
// AppError lives in src-tauri, a Windows-only crate that can't run `cargo
// test` natively in this WSL2 dev environment (only `cargo check --target
// x86_64-pc-windows-msvc`, which can't execute ts-rs's generated export
// tests) — so it's hand-maintained below instead of generated. Keep it in
// sync with src-tauri/src/error.rs by hand.
//
// Usage:
//   cargo test -p system-pulse-core --lib export_bindings   # regenerate target/ts-bindings/
//   node scripts/gen-contracts.mjs                           # regenerate src/lib/contracts.ts
//   node scripts/gen-contracts.mjs --check                   # exit 1 if contracts.ts would change

import { readFileSync, writeFileSync, readdirSync, existsSync } from "fs";
import { fileURLToPath } from "url";
import path from "path";

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, "..");
const bindingsDir = path.join(repoRoot, "target", "ts-bindings");
const outFile = path.join(repoRoot, "src", "lib", "contracts.ts");

if (!existsSync(bindingsDir)) {
  console.error(
    `No bindings found at ${path.relative(repoRoot, bindingsDir)}.\n` +
      "Run this first: cargo test -p system-pulse-core --lib export_bindings",
  );
  process.exit(1);
}

const files = readdirSync(bindingsDir)
  .filter((f) => f.endsWith(".ts"))
  .sort((a, b) => a.localeCompare(b));

if (files.length === 0) {
  console.error(`${path.relative(repoRoot, bindingsDir)} exists but has no .ts files in it.`);
  process.exit(1);
}

const IMPORT_LINE = /^import type \{[^}]*\} from "\.\/[^"]+";\n?/gm;
const GENERATED_BANNER = /^\/\/ This file was generated by \[ts-rs\].*\n/m;

const sections = files.map((file) => {
  let content = readFileSync(path.join(bindingsDir, file), "utf8");
  content = content.replace(GENERATED_BANNER, "");
  content = content.replace(IMPORT_LINE, "");
  return content.trim();
});

const HAND_MAINTAINED = `/**
 * Structured IPC error from the Tauri shell (src-tauri/src/error.rs).
 * Hand-maintained: AppError lives in a Windows-only crate that can't run
 * \`cargo test\` (and therefore ts-rs's export tests) natively in this
 * repo's WSL2 dev environment. Keep this in sync with error.rs by hand.
 */
export type AppError =
  | { kind: "message"; message: string }
  | { kind: "invalidSettings"; message: string }
  | { kind: "notFound"; pid: number }
  | { kind: "accessDenied"; pid: number }
  | { kind: "identityMismatch"; pid: number; expected: UnixMillis; actual: UnixMillis | null };

/** Mirrors \`Settings::default()\` (crates/system-pulse-core/src/settings.rs). */
export const DEFAULT_SETTINGS: Settings = {
  hotkey: "Ctrl+Alt+0",
  launchAtStartup: false,
  compactMode: false,
  refreshIntervalMs: 1000,
  hideToTrayOnClose: true,
};
`;

const banner = `// GENERATED FILE — do not edit by hand.
//
// Source of truth: crates/system-pulse-core/src/{model,types,collector,
// process,settings}.rs, via ts-rs (\`#[derive(TS)] #[ts(export)]\`), except
// AppError (see below). Regenerate with:
//   cargo test -p system-pulse-core --lib export_bindings
//   node scripts/gen-contracts.mjs
`;

const output = banner + "\n" + sections.join("\n\n") + "\n\n" + HAND_MAINTAINED;

if (process.argv.includes("--check")) {
  const current = existsSync(outFile) ? readFileSync(outFile, "utf8") : null;
  if (current !== output) {
    console.error(
      `${path.relative(repoRoot, outFile)} is out of date.\n` +
        "Run: cargo test -p system-pulse-core --lib export_bindings && node scripts/gen-contracts.mjs",
    );
    process.exit(1);
  }
  console.log(`${path.relative(repoRoot, outFile)} is up to date.`);
  process.exit(0);
}

writeFileSync(outFile, output);
console.log(`Wrote ${path.relative(repoRoot, outFile)} from ${files.length} generated type(s).`);
